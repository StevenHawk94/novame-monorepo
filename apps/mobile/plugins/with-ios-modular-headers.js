/**
 * with-ios-modular-headers.js
 *
 * Local Expo config plugin that injects `:modular_headers => true` for the
 * Google pods that break the EAS pod install step.
 *
 * Why we need this:
 *   - GoogleSignIn (9.1.0) pulls in AppCheckCore (11.3.0) transitively.
 *     AppCheckCore is a Swift pod and, under the static-library linkage
 *     this project uses, it must import GoogleUtilities and
 *     RecaptchaInterop as modules. Those two pods do not define module
 *     maps by default, so CocoaPods aborts pod install with:
 *       [!] The Swift pod `AppCheckCore` depends upon `GoogleUtilities`
 *           and `RecaptchaInterop`, which do not define modules.
 *   - CocoaPods' own fix message offers two routes: global
 *     `use_modular_headers!`, or per-pod `:modular_headers => true`.
 *     We take the PER-POD route on purpose: a global use_modular_headers!
 *     is known to trigger a ReactCommon header redefinition during the
 *     Xcode build for RN 0.81 New Architecture. Scoping the flag to only
 *     the two Google pods avoids touching the React/Expo pod graph.
 *   - app.json / expo-build-properties has no field for this, and the
 *     Podfile is regenerated by prebuild (CNG project, no committed
 *     ios/), so the only reliable place to add the line is a config
 *     plugin that patches the generated Podfile via withDangerousMod.
 *
 * 1.0.6 EAS build fix.
 */
const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

// Pods that need module maps generated so the Swift pod AppCheckCore
// can import them under static linkage.
const PODS_NEEDING_MODULAR_HEADERS = ['GoogleUtilities', 'RecaptchaInterop'];

const withIosModularHeaders = (config) => {
  return withDangerousMod(config, [
    'ios',
    (config) => {
      const podfilePath = path.join(
        config.modRequest.platformProjectRoot,
        'Podfile',
      );
      let contents = fs.readFileSync(podfilePath, 'utf-8');

      // Build the lines we want to ensure exist inside the target block.
      const lines = PODS_NEEDING_MODULAR_HEADERS.map(
        (pod) => `  pod '${pod}', :modular_headers => true`,
      );

      // Skip pods already declared with modular_headers to stay idempotent.
      const toInsert = lines.filter((line) => {
        const podName = line.match(/pod '([^']+)'/)[1];
        const already = new RegExp(
          `pod '${podName}'[^\\n]*:modular_headers\\s*=>\\s*true`,
        );
        return !already.test(contents);
      });

      if (toInsert.length === 0) {
        return config;
      }

      // Anchor: insert right after `use_expo_modules!`, which every Expo
      // Podfile contains inside the app target. Fall back to the first
      // `target '...' do` line if the anchor is ever renamed upstream.
      const block = toInsert.join('\n') + '\n';
      if (contents.includes('use_expo_modules!')) {
        contents = contents.replace(
          /(\n[ \t]*use_expo_modules!.*\n)/,
          `$1${block}`,
        );
      } else {
        contents = contents.replace(
          /(\ntarget\s+'[^']+'\s+do\n)/,
          `$1${block}`,
        );
      }

      fs.writeFileSync(podfilePath, contents);
      return config;
    },
  ]);
};

module.exports = withIosModularHeaders;
