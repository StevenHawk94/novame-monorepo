-- Repair only AI-generated absence/disclaimer copy that was mistakenly saved
-- as a memory. User-authored and Use My Words descriptions are never touched.
-- The deterministic source excerpt is the exact journal clause that triggered
-- the item match, so this replacement adds no invented information.

update public.item_memories as memory
set
  raw_excerpt = left(btrim(item.source_excerpt), 500),
  refined_desc = left(btrim(item.source_excerpt), 500),
  description = left(btrim(item.source_excerpt), 500),
  memory_source = 'ai'
from public.reflect_items as item
where memory.user_id = item.user_id
  and memory.reflect_id = item.reflect_id
  and memory.item_id = item.item_id
  and memory.memory_source = 'ai'
  and nullif(btrim(item.source_excerpt), '') is not null
  and (
    lower(btrim(coalesce(memory.description, memory.refined_desc, memory.raw_excerpt, '')))
      ~ 'no (specific )?memor(y|ies)'
    or lower(btrim(coalesce(memory.description, memory.refined_desc, memory.raw_excerpt, '')))
      ~ '(journal|reflection|entry) (does not|doesn''t|did not|didn''t) (mention|include|record|describe)'
    or lower(btrim(coalesce(memory.description, memory.refined_desc, memory.raw_excerpt, '')))
      ~ '(was|were|is|are) not (mentioned|included|recorded|described|provided)'
    or lower(btrim(coalesce(memory.description, memory.refined_desc, memory.raw_excerpt, '')))
      ~ '(not enough|insufficient|no) (specific )?(context|detail|information)'
    or lower(btrim(coalesce(memory.description, memory.refined_desc, memory.raw_excerpt, '')))
      ~ 'nothing (specific )?(was )?(mentioned|included|recorded|described|provided)'
  );

-- Unfinalized drafts will be regenerated by /reflect/enrich. Remove only the
-- same invalid AI keys so they are no longer mistaken for completed memories.
update public.reflect_drafts as draft
set ai_memories = coalesce((
  select jsonb_object_agg(entry.key, entry.value)
  from jsonb_each_text(coalesce(draft.ai_memories, '{}'::jsonb)) as entry
  where not (
    lower(btrim(entry.value)) ~ 'no (specific )?memor(y|ies)'
    or lower(btrim(entry.value))
      ~ '(journal|reflection|entry) (does not|doesn''t|did not|didn''t) (mention|include|record|describe)'
    or lower(btrim(entry.value))
      ~ '(was|were|is|are) not (mentioned|included|recorded|described|provided)'
    or lower(btrim(entry.value))
      ~ '(not enough|insufficient|no) (specific )?(context|detail|information)'
    or lower(btrim(entry.value))
      ~ 'nothing (specific )?(was )?(mentioned|included|recorded|described|provided)'
  )
), '{}'::jsonb)
where draft.finalized_reflect_id is null
  and draft.ai_memories is not null
  and exists (
    select 1
    from jsonb_each_text(draft.ai_memories) as entry
    where lower(btrim(entry.value)) ~ 'no (specific )?memor(y|ies)'
      or lower(btrim(entry.value))
        ~ '(journal|reflection|entry) (does not|doesn''t|did not|didn''t) (mention|include|record|describe)'
      or lower(btrim(entry.value))
        ~ '(was|were|is|are) not (mentioned|included|recorded|described|provided)'
      or lower(btrim(entry.value))
        ~ '(not enough|insufficient|no) (specific )?(context|detail|information)'
      or lower(btrim(entry.value))
        ~ 'nothing (specific )?(was )?(mentioned|included|recorded|described|provided)'
  );
