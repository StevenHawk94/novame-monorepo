export async function testMemoryPhotos({db,query,rpc,check}) {
  const me='00000000-0000-0000-0000-000000000008',partner='00000000-0000-0000-0000-000000000009';
  const key=n=>`30000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
  await db.exec('begin');
  await db.query('insert into profiles(id) values($1),($2)',[me,partner]);
  await db.query('insert into pairings values($1,$2),($2,$1)',[me,partner]);
  const entry=(await rpc('save_memory_room_entry_v1',[me,null,'A memory',null,'photo-memory'])).entryId;
  const prepare=(slot,n,expected=null,actor=me)=>rpc('prepare_memory_photo_v1',[actor,entry,slot,expected,key(n),'a'.repeat(64)]);
  const complete=id=>rpc('complete_memory_photo_v1',[me,id]);
  check((await prepare(0,1,null,partner)).error==='not_found','partner cannot upload to author’s entry');
  check((await prepare(3,2)).error==='invalid_request','fourth slot is rejected server-side');
  let tickets=[];
  for(let slot=0;slot<3;slot++) {
    const t=await prepare(slot,10+slot);tickets.push(t);
    check((await complete(t.ticketId)).applied===true,`slot ${slot} commits`);
  }
  check((await complete(tickets[0].ticketId)).applied===false,'commit retry is idempotent');
  check((await prepare(0,10)).committed===true,'lost upload response returns committed receipt');
  check((await rpc('prepare_memory_photo_v1',[me,entry,0,null,key(10),'b'.repeat(64)])).error==='idempotency_conflict','key cannot be reused for changed bytes');
  check((await rpc('read_memory_photo_v1',[partner,tickets[0].ticketId])).path===tickets[0].path,'current partner can read private photo');
  const state=await rpc('burrow_bootstrap_v1',[partner]);
  const photos=state.memoryEntries.find(x=>x.id===entry).photos;
  check(photos.length===3&&Object.keys(photos[0]).sort().join(',')==='id,slot,updatedAt','bootstrap exposes photo metadata only');
  const t4=await prepare(0,20,tickets[0].ticketId),t5=await prepare(0,21,tickets[0].ticketId);
  check((await complete(t4.ticketId)).applied===true,'replacement commits against exact opened version');
  check((await complete(t5.ticketId)).error==='photo_conflict','concurrent replacement cannot overwrite newer photo');
  check((await complete(tickets[0].ticketId)).applied===false,'old successful replay cannot restore old photo');
  check((await rpc('read_memory_photo_v1',[me,tickets[0].ticketId])).error==='not_found','replaced photo no longer gets signed');
  check((await query('select * from memory_photo_garbage where private_path=$1',[tickets[0].path])).length===1,'replacement queues exact old storage object');
  check((await rpc('delete_memory_photo_v1',[partner,entry,t4.ticketId])).error==='not_found','partner cannot remove author photo');
  check((await rpc('delete_memory_photo_v1',[me,entry,t4.ticketId])).applied===true,'author can delete a photo without removing words');
  check((await rpc('delete_memory_photo_v1',[me,entry,t4.ticketId])).applied===false,'photo deletion replay is harmless');
  check((await complete(t5.ticketId)).error==='upload_expired','explicit deletion cancels older pending replacement');
  const pending=await prepare(0,30),successor=await prepare(0,31);
  await complete(successor.ticketId);await rpc('delete_memory_photo_v1',[me,entry,successor.ticketId]);
  check((await complete(pending.ticketId)).error==='upload_expired','empty-slot upload cannot resurrect photo after successor deleted');
  check((await query('select body from memory_room_entries where id=$1',[entry]))[0].body==='A memory','photo delete preserves words');
  const orphan=await prepare(0,40);
  await db.query("update memory_photo_uploads set created_at=now()-interval '25 hours' where id=$1",[orphan.ticketId]);
  check((await prepare(0,40)).error==='upload_expired','expired pending ticket cannot be uploaded again');
  const firstSweep=await rpc('collect_memory_photo_garbage_v1',[]);
  check(firstSweep.length===0,'cleanup respects grace period');
  check((await complete(orphan.ticketId)).error==='upload_expired','garbage sweep prevents late attachment');
  await db.exec("update memory_photo_garbage set not_before=now()-interval '1 second'");
  const sweep=await rpc('collect_memory_photo_garbage_v1',[]);
  check(sweep.includes(orphan.path)&&!sweep.includes(tickets[1].path),'cleanup includes orphan but never active photo');
  await rpc('delete_memory_room_entry_v1',[me,entry]);
  check((await query('select * from memory_entry_photos where entry_id=$1',[entry])).length===0,'deleting entry retires all photo rows');
  check((await rpc('read_memory_photo_v1',[partner,tickets[1].ticketId])).error==='not_found','deleted entry photos cannot be signed');
  check((await query("select * from moment_events where reference_type='memory_room_entry' and reference_id=$1",[entry])).length===0,'deleted entry removed from Moments');
  check((await prepare(0,50)).error==='not_found','deleted entry cannot receive new upload');
  const next=(await rpc('save_memory_room_entry_v1',[me,null,'Next',null,'next-memory'])).entryId;
  const t=await rpc('prepare_memory_photo_v1',[me,next,0,null,key(51),'a'.repeat(64)]);await complete(t.ticketId);
  const cascadeEntry=(await rpc('save_memory_room_entry_v1',[me,null,'Account cascade',null,'cascade-memory'])).entryId;
  const cascadePhoto=await rpc('prepare_memory_photo_v1',[me,cascadeEntry,0,null,key(52),'a'.repeat(64)]);await complete(cascadePhoto.ticketId);
  await db.query('delete from pairings where user_id in($1,$2)',[me,partner]);
  check((await rpc('read_memory_photo_v1',[partner,t.ticketId])).error==='not_paired','unpair stops new signed links');
  await db.query('delete from memory_room_entries where id=$1',[next]);
  check((await query('select * from memory_photo_garbage where private_path=$1',[t.path])).length===1,'hard deletion cascade leaves durable storage cleanup tombstone');
  await db.query('delete from profiles where id=$1',[me]);
  check((await query('select * from memory_entry_photos where entry_id=$1',[cascadeEntry])).length===0,'profile cascade removes active photo metadata');
  check((await query('select * from memory_photo_garbage where private_path=$1',[cascadePhoto.path])).length===1,'profile cascade preserves object cleanup work without profile FK');
  check(!(await query("select has_column_privilege('authenticated','memory_entry_photos','private_path','select') allowed"))[0].allowed,'authenticated role cannot read private paths');
  check(!(await query("select has_function_privilege('authenticated','complete_memory_photo_v1(uuid,uuid)','execute') allowed"))[0].allowed,'client cannot bypass upload verification via direct RPC');
  await db.exec('rollback');
}
