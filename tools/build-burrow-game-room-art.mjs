/** Map supplied standalone icons to stable game IDs; never modify the artwork. */
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogue = JSON.parse(fs.readFileSync(path.join(root, 'apps/api/src/data/burrow-game-room-v1.json'), 'utf8'));
const iconFolder = 'apps/mobile/assets/burrow-webp/game-room-icons';
const moduleFile = 'apps/mobile/src/lib/burrow-game-room-art.ts';
const mappings = catalogue.games.map(game => ({
  id: game.id,
  // Catalogue titles include trailing emoji; supplied filenames use the English title only.
  filename: game.title.replace(/\s+[^\x00-\x7F].*$/u, '').trim() + '.webp',
}));
assert.equal(mappings.length, 70);
assert.equal(new Set(mappings.map(icon => icon.id)).size, 70);
assert.equal(new Set(mappings.map(icon => icon.filename)).size, 70);
assert.deepEqual(
  fs.readdirSync(path.join(root, iconFolder)).filter(file => /\.webp$/i.test(file)).sort(),
  mappings.map(icon => icon.filename).sort(),
  'Every game must match exactly one supplied icon; missing or unmatched assets need review.',
);
for (const file of ['apps/mobile/assets/burrow-webp/basic-bg.webp']) {
  assert.ok(fs.existsSync(path.join(root, file)), 'Missing retained artwork: ' + file);
}
const source = [
  '// Generated by tools/build-burrow-game-room-art.mjs. All paths must stay static for Metro.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  "export const gameRoomBackground = require('../../assets/burrow-webp/basic-bg.webp') as ImageSourcePropType;",
  'export const gameRoomIcons: Record<string, ImageSourcePropType> = {',
  ...mappings.map(icon => "  '" + icon.id + "': require('../../assets/burrow-webp/game-room-icons/" + icon.filename + "') as ImageSourcePropType,"),
  '};', '',
].join('\n');

if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(path.join(root, moduleFile), 'utf8'), source, 'Game Room art registry needs regeneration.');
  console.log('70 supplied Game Room icons verified; registry is current.');
} else {
  // Emit a patch for apply_patch instead of overwriting unrelated working-tree edits.
  const previous = fs.readFileSync(path.join(root, moduleFile), 'utf8');
  console.log('*** Begin Patch\n*** Update File: ' + path.join(root, moduleFile) + '\n@@\n' +
    previous.trimEnd().split('\n').map(line => '-' + line).join('\n') + '\n' +
    source.trimEnd().split('\n').map(line => '+' + line).join('\n') + '\n*** End Patch');
}
