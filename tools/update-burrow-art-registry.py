"""Rebuild Metro's literal WebP imports and visible bounds after an art refresh.

Default-* is ordinal one. Keep identifiable older variants in their existing
ordinal order so a renamed file does not silently change a purchased loadout.
Only metadata is generated: source artwork is never modified.
"""
from pathlib import Path
from io import BytesIO
import json
import re
import subprocess
import sys

import numpy as np
from PIL import Image, ImageOps
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "apps/mobile/assets"
OUTPUT = ROOT / "apps/mobile/src/lib/burrow-art-assets.ts"
GROUPS = {
    "cabinets": "Dresser", "shelves": "bookself", "light_strings": "light string",
    "windows": "windows", "ladders": "ladder", "tables": "table",
    "frames": "photo frame", "lamps": "lamp", "couple_dolls": "interative toys on dresser",
    "shelf_decor": "bookshelf decor", "dresser_plants": "succulent on dresser",
    "rugs": "rug", "cushions": "cusion", "vases": "flower", "music_players": "radio",
    "wallpapers": "wallpaper", "backgrounds": "background-season",
}
previous = OUTPUT.read_text()


def thumbnail(image):
    image = image.convert("RGBA")
    image = image.crop(image.getchannel("A").getbbox())
    bg = Image.new("RGBA", image.size, "#FFF5E8")
    bg.alpha_composite(image)
    return np.asarray(bg.convert("RGB").resize((48, 48)), dtype=float)


def photo_bounds(image, category, close_gaps=0):
    pixels = np.asarray(image.convert("RGBA"))
    if category == "frames":
        # The refreshed frames contain a blue photo placeholder, not an alpha
        # hole. Render the user's 201:290 image ON TOP of that inset.
        mask = (pixels[:, :, 2] > pixels[:, :, 0] * 1.4) & (pixels[:, :, 1] < 130) & (pixels[:, :, 3] > 128)
    else:
        solid = pixels[:, :, 3] >= 32
        if close_gaps:
            solid = ndimage.binary_closing(solid, iterations=close_gaps)
        mask = ~solid
    labels, count = ndimage.label(mask)
    candidates = []
    for label, slices in enumerate(ndimage.find_objects(labels), 1):
        if slices is None:
            continue
        ys, xs = slices
        if category != "frames" and (xs.start == 0 or ys.start == 0 or xs.stop == image.width or ys.stop == image.height):
            continue
        area = np.count_nonzero(labels[ys, xs] == label)
        if area > 500 and .15 < (ys.start + ys.stop) / 2 / image.height < .65:
            candidates.append((area, [xs.start, ys.start, xs.stop, ys.stop]))
    if candidates:
        detected = max(candidates)[1]
        if category == "frames":
            canonical = [150, 128, 351, 418]
            if any(abs(actual - expected) > 2 for actual, expected in zip(detected, canonical)):
                raise ValueError(f"Frame opening changed: {detected}, expected {canonical}")
            # Compression changes thresholded edges by 1px, not the layout.
            return canonical
        return detected
    if category == "couple_dolls" and close_gaps < 16:
        return photo_bounds(image, category, close_gaps + 4)
    return None


def entry(file, category):
    image = Image.open(file).convert("RGBA")
    bounds = image.getchannel("A").point(lambda alpha: 255 if alpha >= 12 else 0).getbbox()
    if not bounds:
        raise ValueError(f"Empty artwork: {file}")
    name = file.stem.removeprefix("Default-")
    fields = f"source: require({json.dumps('../../assets/' + file.relative_to(ASSETS).as_posix(), ensure_ascii=False)}), name: {json.dumps(name, ensure_ascii=False)}, width: {image.width}, height: {image.height}, bounds: {list(bounds)}"
    if category == "wallpapers":
        thumbnail_file = ASSETS / "burrow-webp/wallpaper-thumbnails" / file.name
        thumbnail_file.parent.mkdir(exist_ok=True)
        ImageOps.fit(image, (256, 256), method=Image.Resampling.LANCZOS).save(thumbnail_file, "WEBP", quality=90)
        fields += f", thumbnail: require({json.dumps('../../assets/' + thumbnail_file.relative_to(ASSETS).as_posix(), ensure_ascii=False)})"
    if category in ("frames", "couple_dolls"):
        photo = photo_bounds(image, category)
        if not photo:
            raise ValueError(f"Missing photo inset: {file}")
        fields += f", photoBounds: {photo}"
    return "    { " + fields + " },"


lines = ["import type { ImageSource } from 'expo-image';", "import type { MajorUpdateCatalogItem } from './app-major-update-api';", "",
    "export type BurrowArtAsset = { source: ImageSource; thumbnail?: ImageSource; name?: string; width: number; height: number; bounds: readonly [number, number, number, number]; photoBounds?: readonly [number, number, number, number] };",
    "// Generated by tools/update-burrow-art-registry.py. Default-* always comes first.",
    "// Visible alpha bounds, not transparent margins, define furniture anchors.",
    "export const BURROW_ART: Record<string, readonly BurrowArtAsset[]> = {"]
for category, directory in GROUPS.items():
    folder = ASSETS / "burrow-webp/room decoration" / directory
    files = sorted(folder.glob("*.webp"), key=lambda file: file.name)
    default = [file for file in files if file.name.startswith("Default-")]
    if len(default) != 1:
        raise ValueError(f"Expected one Default asset: {directory}")
    ordered = default[:]
    remaining = [file for file in files if file not in ordered]
    block = re.search(r"  " + category + r": \[(.*?)\n  \],", previous, re.S)
    if block:
        old_paths = [file for _, file in re.findall(r"require\((['\"])../../assets/(.*?)\1\)", block[1])]
        for index, old_path in enumerate(old_paths):
            if index == 0 or not remaining:
                continue
            old_file = ASSETS / old_path
            match = next((file for file in remaining if file == old_file), None)
            if match is None:
                old = subprocess.run(["git", "show", f"HEAD:apps/mobile/assets/{old_path}"], cwd=ROOT, capture_output=True)
                if old.returncode == 0:
                    old_thumb = thumbnail(Image.open(BytesIO(old.stdout)))
                    distance, candidate = min((float(np.mean((thumbnail(Image.open(file)) - old_thumb) ** 2)), file) for file in remaining)
                    if distance < 2500:
                        match = candidate
            if match is not None:
                ordered.append(match)
                remaining.remove(match)
    ordered += remaining
    lines += [f"  {category}: [", *(entry(file, category) for file in ordered), "  ],"]
lines += ["  // The removed poster collection is intentionally not required by Metro.", "  posters: [],", "};", "",
    "// Season products reuse the full cave/floor layer, separate from wallpaper.",
    "BURROW_ART.seasons = BURROW_ART.backgrounds;"]
tail = previous[previous.index("export const BURROW_BACKGROUNDS ="):]
tail = tail.replace("  loveLetter:", "  bunny: { source: require('../../assets/burrow-webp/home-bunny.webp'), width: 600, height: 600, bounds: [83, 40, 533, 600] } as BurrowArtAsset,\n  loveLetter:") if "  bunny:" not in tail else tail
tail = tail.replace("const ordinal = item?.metadata.artOrdinal ?? 1;", "// Starter art follows the supplied Default-* file, regardless of old metadata.\n  const ordinal = item?.metadata.starter ? 1 : item?.metadata.artOrdinal ?? 1;")
OUTPUT.write_text("\n".join(lines) + tail)
print(f"Registered {sum(len(list((ASSETS / 'burrow-webp/room decoration' / folder).glob('*.webp'))) for folder in GROUPS.values())} current WebP assets")

if len(sys.argv) > 1:
    # Catalog identities survive an art refresh. Preserve existing prices and
    # ownership; new variants use the established 150-carrot decor price.
    legacy_ids = {
        "cabinets": ["storage_burrow_01", "placeholder_storage_02"],
        "windows": ["window_sunny_01", "placeholder_windows_02"],
        "lamps": ["lamp_acorn_01", "placeholder_lamps_02"],
        "vases": ["plant_daisy_01", "placeholder_plants_02"],
        "cushions": ["cushion_moss_01", "placeholder_cushions_02"],
        "tables": ["table_stump_01", "placeholder_tables_02"],
        "rugs": ["rug_leaf_01", "placeholder_rugs_02"],
        "music_players": ["placeholder_music_players_01", "placeholder_music_players_02"],
        "frames": ["placeholder_frames_01", "placeholder_frames_02"],
        "couple_dolls": ["placeholder_couple_dolls_01", "placeholder_couple_dolls_02"],
    }
    slots = dict(zip(GROUPS, ["cabinet", "shelf", "light_string", "window", "ladder", "table", "frame", "lamp", "couple_doll", "shelf_decor", "dresser_plant", "rug", "cushion", "vase", "music_player", "wallpaper", "background"]))
    registry = OUTPUT.read_text()
    quote = lambda value: "'" + value.replace("'", "''") + "'"
    values = []
    for category in GROUPS:
        if category == "backgrounds":
            continue  # Seasons remain fixed, not a new Shop section.
        block = re.search(r"  " + category + r": \[(.*?)\n  \],", registry, re.S)[1]
        entries = re.findall(r'source: require\("(.*?)"\), name: (".*?"),', block)
        for index, (file, encoded_name) in enumerate(entries):
            ordinal = index + 1
            ids = legacy_ids.get(category, [])
            stable_id = ids[index] if index < len(ids) else f"burrow_art_{category}_{ordinal:02}"
            values.append("  (" + ", ".join([quote(stable_id), quote(category), quote(slots[category]), str(ordinal), quote(json.loads(encoded_name)), quote(file.removeprefix('../../assets/'))]) + ")")
    sql = """-- Refreshed named WebP art. Keep stable IDs, ownership and existing prices.
-- Default variants remain free starter items; added variants follow the
-- existing 150-carrot price. No user room/loadout or photo is reset.
with art(stable_id, category, slot, ordinal, title, file) as (values
""" + ",\n".join(values) + """
)
insert into public.catalog_items (stable_id, revision_id, item_type, category,
  title, description, price, plus_only, tradable, tags, drop_weight, asset, metadata, is_placeholder)
select art.stable_id, coalesce((select value from public.app_config
  where key='app_major_update_content_revision'), 'burrow-v1-placeholder'),
  'decor', art.category, art.title, 'A decoration for your Burrow.',
  case when art.ordinal=1 then 0 else 150 end, false, true,
  array['burrow',art.category], 0,
  jsonb_build_object('renderer','bundled','artCategory',art.category,'ordinal',art.ordinal,'file',art.file),
  jsonb_build_object('slot',art.slot,'starter',art.ordinal=1,'artOrdinal',art.ordinal,'artName',art.title), false
from art
on conflict (stable_id) do update set title=excluded.title,
  asset=catalog_items.asset || excluded.asset,
  metadata=catalog_items.metadata || excluded.metadata,
  is_placeholder=false, updated_at=now();

-- Removed art stays in inventories/history but is no longer offered for sale.
update public.catalog_items set status='retired', updated_at=now()
where category='posters' and item_type='decor';

-- Existing users also receive the new default wall immediately.
insert into public.user_inventory (owner_id,item_id,source)
select profiles.id, item.stable_id, 'starter'
from public.profiles cross join public.catalog_items item
where item.category='wallpapers' and item.metadata->>'starter'='true' and item.status='active'
on conflict (owner_id,item_id) do nothing;
"""
    migration = ROOT / sys.argv[1]
    migration.write_text(sql)
    print(f"Generated {migration.name}: {len(values)} named catalog items")
